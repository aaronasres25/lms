<?php

namespace App\Support;

/** Builds a tiny but valid multi-page PDF (no libraries) so demo e-books open in the PDF.js reader. */
class DemoPdf
{
    public static function make(string $title, int $pages = 6): string
    {
        $pages = max(1, $pages);
        $title = self::esc($title);
        $objects = [
            1 => '<< /Type /Catalog /Pages 2 0 R >>',
            3 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        ];

        $pageIds = [];
        $next = 4;
        for ($i = 1; $i <= $pages; $i++) {
            $pageId = $next++;
            $contentId = $next++;
            $pageIds[] = $pageId;

            $stream = "BT /F1 26 Tf 72 740 Td ({$title}) Tj ET\n"
                . "BT /F1 14 Tf 72 700 Td (Page {$i} of {$pages}) Tj ET\n"
                . "BT /F1 12 Tf 72 660 Td (Demo e-book generated by the LMS demo-data command.) Tj ET\n"
                . "BT /F1 11 Tf 72 630 Td (Your reading position is saved automatically when you sign in.) Tj ET";

            $objects[$pageId] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents {$contentId} 0 R >>";
            $objects[$contentId] = '<< /Length ' . strlen($stream) . " >>\nstream\n{$stream}\nendstream";
        }
        $objects[2] = '<< /Type /Pages /Kids [' . implode(' ', array_map(fn ($id) => "{$id} 0 R", $pageIds)) . "] /Count {$pages} >>";
        ksort($objects);

        $pdf = "%PDF-1.4\n";
        $offsets = [];
        foreach ($objects as $id => $body) {
            $offsets[$id] = strlen($pdf);
            $pdf .= "{$id} 0 obj\n{$body}\nendobj\n";
        }

        $size = max(array_keys($objects)) + 1;
        $xref = strlen($pdf);
        $pdf .= "xref\n0 {$size}\n0000000000 65535 f \n";
        for ($i = 1; $i < $size; $i++) {
            $pdf .= sprintf("%010d 00000 n \n", $offsets[$i]);
        }
        return $pdf . "trailer\n<< /Size {$size} /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF";
    }

    private static function esc(string $text): string
    {
        $text = preg_replace('/[^\x20-\x7E]/', '?', $text) ?? '';
        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $text);
    }
}
